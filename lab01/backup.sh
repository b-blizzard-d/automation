#!/bin/bash
#
# backup.sh — скрипт для создания резервной копии каталога.
# Лабораторная работа №1, вводный курс Linux, USM.
# Автор: Метельская Даниела
#
# Использование: ./backup.sh <каталог> [каталог_назначения]
#   <каталог>            — каталог, который нужно сохранить (обязательный аргумент)
#   [каталог_назначения] — куда положить архив (необязательный, по умолчанию /backup)

# ------------------------------------------------------------
# 1. Проверка аргументов
# ------------------------------------------------------------
# $# — количество переданных скрипту аргументов.
# Если аргументов нет, то непонятно, что сохранять, поэтому
# выводим сообщение об ошибке и подсказку по использованию.
# Сообщения об ошибках выводятся в stderr (>&2).
if [ $# -lt 1 ]; then
    echo "Ошибка: не указан каталог для резервного копирования." >&2
    echo "Использование: ./backup.sh <каталог> [каталог_назначения]" >&2
    exit 1    # ненулевой код выхода означает ошибку
fi

# Первый аргумент — каталог-источник.
SOURCE_DIR="$1"

# ------------------------------------------------------------
# 2. Каталог назначения
# ------------------------------------------------------------
# Конструкция ${2:-/backup} подставляет второй аргумент,
# а если он не передан (или пустой) — значение /backup.
BACKUP_DIR="${2:-/backup}"

# ------------------------------------------------------------
# 3. Проверка существования каталогов
# ------------------------------------------------------------
# Проверка [ -d путь ] истинна, если путь существует и это каталог.
# Восклицательный знак ! инвертирует условие: «если НЕ каталог».

# 3.1. Каталог-источник должен существовать.
if [ ! -d "$SOURCE_DIR" ]; then
    echo "Ошибка: каталог-источник \"$SOURCE_DIR\" не найден." >&2
    exit 1
fi

# 3.2. Каталог назначения тоже должен существовать.
# Скрипт намеренно НЕ создаёт его сам, чтобы случайная опечатка
# в пути не приводила к появлению лишних каталогов.
if [ ! -d "$BACKUP_DIR" ]; then
    echo "Ошибка: каталог назначения \"$BACKUP_DIR\" не существует. Создайте его вручную." >&2
    exit 1
fi

# ------------------------------------------------------------
# 4. Формирование имени архива
# ------------------------------------------------------------
# dirname возвращает родительский каталог (например, /home/daniela),
# basename — имя самого каталога (например, documents).
# Это нужно, чтобы в архив попал только сам каталог,
# а не полный путь от корня файловой системы.
PARENT_DIR="$(dirname "$SOURCE_DIR")"
DIR_NAME="$(basename "$SOURCE_DIR")"

# Текущая дата и время в формате ГГГГ-ММ-ДД_ЧЧ-ММ, например 2026-10-26_15-30.
DATE="$(date +%Y-%m-%d_%H-%M)"

# Итоговое имя архива, например documents_backup_2026-10-26_15-30.tar.gz.
ARCHIVE_NAME="${DIR_NAME}_backup_${DATE}.tar.gz"

# ------------------------------------------------------------
# 5. Создание архива
# ------------------------------------------------------------
# Ключи tar:
#   -c — создать новый архив;
#   -z — сжать его с помощью gzip;
#   -f — имя файла архива;
#   -C — перед архивированием перейти в указанный каталог.
tar -czf "$BACKUP_DIR/$ARCHIVE_NAME" -C "$PARENT_DIR" "$DIR_NAME"

# $? — код завершения последней команды (0 — успех).
if [ $? -ne 0 ]; then
    echo "Ошибка при создании архива." >&2
    exit 1
fi

# ------------------------------------------------------------
# 6. Результат
# ------------------------------------------------------------
# Сообщаем пользователю, где лежит готовый архив.
echo "Резервная копия успешно создана: $BACKUP_DIR/$ARCHIVE_NAME"

# Успешное завершение скрипта.
exit 0
